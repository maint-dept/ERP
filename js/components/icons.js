/**
 * Returns a standardized inline SVG icon string
 */
export function icon(name, options = {}) {
  const size = options.size || (typeof options === 'number' ? options : 16);
  const cls = (options.className || '') + (options.class ? ` ${options.class}` : '');
  const strokeWidth = options.strokeWidth || 2;
  const style = options.style || '';
  const color = options.color || 'currentColor';
  const path = SVG_PATHS[name] || SVG_PATHS['alertCircle'];

  return `<span class="erp-icon erp-icon-${name}${cls ? ` ${cls}` : ''}" style="display:inline-flex;align-items:center;justify-content:center;line-height:1;vertical-align:-0.15em;${style}"><svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" style="display:block;pointer-events:none;flex-shrink:0;">${path}</svg></span>`;
}

