  window.erpIcons = { icon, replaceEmojiInHtml, enhanceDomIcons, setupAutoDomEnhancer, SVG_PATHS, EMOJI_MAP };
  window.erpIcon = icon;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => setupAutoDomEnhancer());
  } else {
    setupAutoDomEnhancer();
  }
